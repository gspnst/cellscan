def country(mcc: int) -> tuple[str, str] | None:
    """(ISO code, name) for an MCC."""
    if mcc in (1, 999):
        return ("XX", "Test network")
    if mcc == 901:
        return ("XX", "International")
    return COUNTRIES.get(mcc)


def flag(iso: str) -> str:
    if len(iso) != 2 or iso == "XX":
        return ""
    return "".join(chr(127397 + ord(c)) for c in iso.upper())


def operator_name(mcc: int, mnc: int) -> str | None:
    return OPERATORS.get((mcc, mnc))


def describe(mcc: int | None, mnc: int | None) -> str:
    from .models import format_plmn

    if mcc is None:
        return "unknown network"
    c = country(mcc)
    if mnc is not None:
        name = operator_name(mcc, mnc) or format_plmn(mcc, mnc)
        return f"{name} ({c[1]})" if c else name
    return c[1] if c else f"MCC {mcc}"


def is_known_mcc(mcc: int) -> bool:
    return mcc in COUNTRIES or mcc in (1, 999, 901)
